-- Guarda teléfonos recolectados con una referencia libre para cualquier cartera.
-- Conserva los datos de referencia 5 antes de retirar las columnas fijas.

DO $$
DECLARE
    account_id_type TEXT;
BEGIN
    SELECT format_type(attribute.atttypid, attribute.atttypmod)
    INTO account_id_type
    FROM pg_attribute AS attribute
    JOIN pg_class AS relation
      ON relation.oid = attribute.attrelid
    JOIN pg_namespace AS schema
      ON schema.oid = relation.relnamespace
    WHERE schema.nspname = 'public'
      AND relation.relname = 'carteras'
      AND attribute.attname = 'id_cartera'
      AND NOT attribute.attisdropped;

    IF account_id_type IS NULL THEN
        RAISE EXCEPTION 'No se encontró public.carteras.id_cartera.';
    END IF;

    EXECUTE format(
        'CREATE TABLE IF NOT EXISTS public.numeros_recolectados (
            id_numero BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            fk_cartera %s NOT NULL
                REFERENCES public.carteras (id_cartera)
                ON DELETE CASCADE,
            telefono TEXT,
            referencia TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now()
        )',
        account_id_type
    );
END
$$;

CREATE INDEX IF NOT EXISTS numeros_recolectados_cartera_idx
    ON public.numeros_recolectados (fk_cartera, id_numero);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'carteras'
          AND column_name = 'ref5_nombre'
    ) AND EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'carteras'
          AND column_name = 'ref5_tel'
    ) AND EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'carteras'
          AND column_name = 'ref5_parentesco'
    ) AND EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'carteras'
          AND column_name = 'ref5_domicilio'
    ) THEN
        EXECUTE $migration$
            INSERT INTO public.numeros_recolectados (
                fk_cartera,
                telefono,
                referencia
            )
            SELECT
                cartera.id_cartera,
                NULLIF(trim(cartera.ref5_tel), ''),
                COALESCE(
                    NULLIF(
                        concat_ws(
                            ' · ',
                            NULLIF(trim(cartera.ref5_nombre), ''),
                            NULLIF(trim(cartera.ref5_parentesco), ''),
                            NULLIF(trim(cartera.ref5_domicilio), '')
                        ),
                        ''
                    ),
                    'Referencia 5'
                )
            FROM public.carteras AS cartera
            WHERE (
                   NULLIF(trim(cartera.ref5_nombre), '') IS NOT NULL
                OR NULLIF(trim(cartera.ref5_tel), '') IS NOT NULL
                OR NULLIF(trim(cartera.ref5_parentesco), '') IS NOT NULL
                OR NULLIF(trim(cartera.ref5_domicilio), '') IS NOT NULL
            )
              AND NOT EXISTS (
                  SELECT 1
                  FROM public.numeros_recolectados AS saved
                  WHERE saved.fk_cartera = cartera.id_cartera
                    AND saved.telefono IS NOT DISTINCT FROM
                        NULLIF(trim(cartera.ref5_tel), '')
                    AND saved.referencia = COALESCE(
                        NULLIF(
                            concat_ws(
                                ' · ',
                                NULLIF(trim(cartera.ref5_nombre), ''),
                                NULLIF(trim(cartera.ref5_parentesco), ''),
                                NULLIF(trim(cartera.ref5_domicilio), '')
                            ),
                            ''
                        ),
                        'Referencia 5'
                    )
              )
        $migration$;
    END IF;
END
$$;

ALTER TABLE public.carteras
    DROP COLUMN IF EXISTS ref5_nombre,
    DROP COLUMN IF EXISTS ref5_tel,
    DROP COLUMN IF EXISTS ref5_parentesco,
    DROP COLUMN IF EXISTS ref5_domicilio;

GRANT SELECT, INSERT ON public.numeros_recolectados TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.numeros_recolectados_id_numero_seq
    TO service_role;
